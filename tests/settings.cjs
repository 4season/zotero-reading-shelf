const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const prefs=new Map();
const listeners=new Map();
let root=null;
const checkbox={localName:'checkbox',attrs:{'data-sl-ko':'크기 숨기기','data-sl-en':'Hide size'},getAttribute(key){return this.attrs[key];},setAttribute(key,value){this.attrs[key]=value;}};
const color={value:'#c76a6a',getAttribute:key=>key==='data-sl-color'?'urgentColor':key==='data-sl-depends'?'matrixBorders':null,setAttribute(){}};
const borderControl={getAttribute:()=> 'matrixMode',setAttribute(){}};
const shadowControl={getAttribute:()=> 'shadowStrength',setAttribute(){}};
const document={getElementById:()=>root,addEventListener:(event,fn,capture)=>{assert.equal(capture,true);listeners.set(event,fn);}};
const ctx=vm.createContext({document,Zotero:{Prefs:{get:key=>prefs.get(key),set:(key,value)=>prefs.set(key,value)}},setTimeout:fn=>fn()});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../settings.js'),'utf8'),ctx);
assert.equal(checkbox.attrs.label,undefined);
const makeLabel=(localName,ko,en)=>({localName,attrs:{'data-sl-ko':ko,'data-sl-en':en,value:ko},hasAttribute(key){return key in this.attrs;},getAttribute(key){return this.attrs[key];},setAttribute(key,value){this.attrs[key]=value;}});
const label=makeLabel('label','그림자','Shadow');
const option=makeLabel('menuitem','보통','Medium');
const heading=makeLabel('h3','디자인','Appearance');
const menu={selectedItem:option,setAttribute(key,value){this[key]=value;}};
root={id:'sl-settings',querySelectorAll:selector=>selector==='[data-sl-en]'?[checkbox,label,option,heading]:selector==='menulist'?[menu]:selector==='[data-sl-depends]'?[borderControl,color,shadowControl]:[color]};
listeners.get('load')({target:root});
assert.equal(checkbox.attrs.label,'크기 숨기기');
prefs.set('extensions.reading-shelf.language','en');
listeners.get('command')({target:{closest:()=>root}});
assert.equal(checkbox.attrs.label,'Hide size');
assert.equal(label.attrs.value,'Shadow');
assert.equal(option.attrs.label,'Medium');
assert.equal(heading.textContent,'Appearance');
assert.equal(menu.label,'Medium');
color.value='#112233';listeners.get('change')({target:color});
assert.equal(prefs.get('extensions.reading-shelf.urgentColor'),'#112233');
color.value='invalid';listeners.get('change')({target:color});
assert.equal(prefs.get('extensions.reading-shelf.urgentColor'),'#112233');
listeners.get('showing')({target:root});
assert.equal(color.value,'#112233');
assert.equal(borderControl.disabled,true);
assert.equal(color.disabled,true);
prefs.set('extensions.reading-shelf.matrixMode',true);
prefs.set('extensions.reading-shelf.matrixBorders',true);
listeners.get('command')({target:{closest:selector=>selector==='#sl-settings'?root:null}});
assert.equal(borderControl.disabled,false);
assert.equal(color.disabled,false);
prefs.set('extensions.reading-shelf.matrixBorders',false);
listeners.get('command')({target:{closest:selector=>selector==='#sl-settings'?root:null}});
assert.equal(color.disabled,true);
assert.equal(prefs.get('extensions.reading-shelf.urgentColor'),'#112233');
prefs.set('extensions.reading-shelf.shadowStrength','off');
listeners.get('change')({target:{getAttribute(){},closest:()=>root}});
assert.equal(shadowControl.disabled,true);
console.log('Settings script-before-fragment lifecycle, language menu and validated color persistence passed');

const statusColor={value:'#ac458e',getAttribute:key=>key==='data-sl-color'?'plannedColor':null};
listeners.get('change')({target:statusColor});
assert.equal(prefs.get('extensions.reading-shelf.plannedColor'),'#ac458e');
statusColor.value='url(unsafe)';listeners.get('change')({target:statusColor});
assert.equal(prefs.get('extensions.reading-shelf.plannedColor'),'#ac458e');

const reset={getAttribute:key=>key==='data-sl-reset-colors'?'status':null,closest(){return this;}};
prefs.set('extensions.reading-shelf.plannedColor','#ff00ff');
prefs.set('extensions.reading-shelf.urgentColor','#112233');
listeners.get('command')({target:reset});
assert.equal(prefs.get('extensions.reading-shelf.plannedColor'),'#356b24');
assert.equal(prefs.get('extensions.reading-shelf.completedColor'),'#6750a4');
assert.equal(prefs.get('extensions.reading-shelf.urgentColor'),'#112233');
reset.getAttribute=key=>key==='data-sl-reset-colors'?'all':null;
listeners.get('command')({target:reset});
assert.equal(prefs.get('extensions.reading-shelf.urgentColor'),'#c76a6a');
console.log('Scoped and complete color resets preserve unrelated preferences');

statusColor.value='#284ba7';listeners.get('input')({target:statusColor});
assert.equal(prefs.get('extensions.reading-shelf.plannedColor'),'#284ba7');
const modeCheckbox={localName:'checkbox',checked:true,getAttribute:()=> 'extensions.reading-shelf.hideModeControl',closest(selector){return selector.startsWith('checkbox')?this:null;}};
listeners.get('command')({target:modeCheckbox});
assert.equal(prefs.get('extensions.reading-shelf.hideModeControl'),true);
console.log('Native checkbox command persistence and live macOS color-panel input passed');
